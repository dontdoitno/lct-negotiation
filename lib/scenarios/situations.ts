/**
 * Готовые ситуации для конструктора.
 *
 * Пресет описывает только обстановку: кто с кем разговаривает, из-за чего и что
 * каждая сторона на самом деле хочет. Характер собеседника он не трогает
 * намеренно: его подставляет пресет тона, поэтому любая ситуация играется всеми
 * тремя характерами и из семи заготовок получается двадцать один разговор.
 *
 * Тексты здесь черновые. Это отправная точка для администратора, а матрицу
 * реакций и пороги всё равно стоит проверить тест-прогоном.
 */

