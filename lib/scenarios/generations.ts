export const GENERATION_OPTIONS = Object.values(GENERATION_PRESETS).map((g) => ({
  value: g.id,
  label: `${g.label} · ${g.years}`,
}));

const IDS = new Set<string>(Object.keys(GENERATION_PRESETS));

export function isGenerationId(value: unknown): value is GenerationId {
  return typeof value === "string" && IDS.has(value);
}
