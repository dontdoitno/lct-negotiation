/**
 * Поколение собеседника: четвёртая ось движка рядом с направлением,
 * характером и темой.
 *
 * Характер задаёт стратегию в конфликте и матрицу реакций. Поколение задаёт
 * контекст: что человек ценит, что считает уважением, как говорит и чего
 * боится. Одно другое не заменяет: тревожный икс и тревожный зумер оба
 * тревожные, но боятся разного.
 *
 * Поле необязательное. Без него разговор работает ровно как раньше, просто в
 * промт не уходит блок поколения.
 *
 * Границы взяты из `inner_docs/GENERATIONS.md`, рабочий вариант на 2026 год.
 * Единых границ не существует: российская школа сдвигает их на пять-десять лет
 * относительно американской периодизации.
 */

export interface GenerationPreset {
  id: GenerationId;
  label: string;
  /** Годы рождения и возраст на 2026 год. Видно администратору при выборе. */
  years: string;
  /** Блок, который вставляется в системный промт после темперамента. */
  promptBlock: string;
  /** Что задевает дополнительно к триггерам характера. */
  triggers: string[];
  /** Что располагает дополнительно к тому, что располагает характер. */
  soothers: string[];
  /** Типичные скрытые интересы. Подсказка администратору для слоёв. */
  hiddenInterestHints: string[];
  /** Как говорит: администратору для первой реплики и реплик офлайн-режима. */
  speechMarkers: string;
}

