/**
 * Тема «Разбор полётов» — тренажёр управленческих переговоров.
 *
 * Направление: измерительный прибор, а не чат. Продукт держится на том, что
 * состояние собеседника считает детерминированный движок, а не нейросеть, —
 * поэтому интерфейс должен читаться как откалиброванная панель показаний:
 * чертёжная сетка, честные цифры, один акцент. Отсюда чертёжная светлая
 * палитра экрана звонка (серое полотно + синяя «чернильная» линия), которую
 * эта тема продолжает, а не заменяет.
 *
 * Сборка после любой правки (валидирует тему и обновляет типы):
 *   npx astryx theme build theme.ts
 */

import {defineTheme} from '@astryxdesign/core/theme';

export const razborTheme = defineTheme({
  name: 'razbor',

  /**
   * Синий — единственный цвет, не занятый метриками: сопротивление (красный),
   * открытость (зелёный), адаптивность (фиолетовый), интересы (янтарный) уже
   * разобрали остальной спектр. Акцент обязан от них отличаться, иначе кнопка
   * читается как показание прибора.
   *
   * Оттенок — чуть глубже и менее «бутстраповский», чем исходный #2563EB, в
   * сторону чертёжных чернил; в тёмной схеме светлее, чтобы держать контраст.
   *
   * contrast: 'high' — экран звонка это плотный дата-UI (шкалы, чипы дельт,
   * таймлайн), там шире разрыв тонов работает на читаемость.
   */
  color: {accent: ['#2456CE', '#6E9BFF'], neutralStyle: 'neutral', contrast: 'high'},

  /**
   * Шрифты НЕ загружаются темой — она только называет семейства. Здесь
   * намеренно названы ровно те три, что уже подключены через next/font в
   * app/layout.tsx (и, что критично для русского интерфейса, с подключённой
   * кириллицей). Назвать что-то другое — значит молча уехать на fallback.
   *
   * ratio 1.125 — плотная шкала: на экране звонка соседствуют подписи 11px и
   * заголовки 19px, широкие шаги здесь только разболтали бы сетку.
   */
  typography: {
    scale: {base: 16, ratio: 1.125},
    body: {family: 'Manrope', fallbacks: '-apple-system, system-ui, sans-serif'},
    heading: {
      family: 'Unbounded',
      fallbacks: '-apple-system, system-ui, sans-serif',
      weight: 'semibold',
      weights: {1: 'bold', 2: 'bold'},
    },
    code: {family: 'JetBrains Mono', fallbacks: '"SF Mono", ui-monospace, monospace'},
  },

  /** Чертёжная подача любит прямые углы: шаг радиуса мельче стандартного. */
  radius: {base: 4, multiplier: 0.75},

  /**
   * Быстро и точно, без кинематографичности: реплики уже печатаются с
   * задержкой, и если шкалы будут «доезжать» долго, ход начнёт ощущаться
   * вязким. medium держит анимацию шкал — её видно, но она не задерживает.
   */
  motion: {fast: 120, medium: 280, slow: 600, ratio: 0.75},

  tokens: {
    // Полотно и бумага — ровно те, что уже стоят на экране звонка.
    '--color-background-body': ['#EFEFEC', '#111112'],
    '--color-background-surface': ['#FFFFFF', '#1F1F22'],
    '--focus-outline-color': 'var(--color-accent)',
  },

  /**
   * Шесть метрик — собственный семантический словарь продукта, не входящий ни
   * в одну стандартную роль дизайн-системы, поэтому живут в localTokens.
   *
   * Значения из тёмной версии интерфейса нельзя было перенести как есть: они
   * подбирались под тёмный фон и на светлом полотне теряют контраст. Для
   * светлой схемы взяты затемнённые варианты тех же оттенков, для тёмной —
   * исходные.
   *
   * Контрастная гарантия генератора сюда НЕ распространяется (она покрывает
   * только то, что генерит блок `color`), поэтому пары измерены вручную.
   * Проверять надо против ОБОИХ фонов: метрики выводятся и на белых карточках,
   * и на сером полотне — первая версия проходила на белом, но проваливалась
   * на полотне.
   *
   *   светлая схема   на #FFFFFF / на #EFEFEC
   *     resistance    5.43 / 4.71
   *     trust         5.42 / 4.71
   *     adapt         5.62 / 4.88
   *     insight       5.35 / 4.65
   *   тёмная схема    на #1F1F22
   *     5.01 · 7.34 · 5.94 · 7.92
   *
   * Сопротивление намеренно единственная «тревожная» роль: это единственная
   * метрика, у которой рост — ухудшение.
   */
  localTokens: {
    '--metric-resistance': ['#BE3C28', '#E8654F'],
    '--metric-trust': ['#16785B', '#49C19A'],
    '--metric-adapt': ['#5259D4', '#8B93F5'],
    '--metric-insight': ['#8F6211', '#E0AB52'],
  },

  // components: намеренно пусто. Приложение сейчас свёрстано на Tailwind и не
  // рендерит ни одного компонента Astryx — переопределения для button/card
  // скомпилировались бы в CSS, который ничему не соответствует. Добавлять по
  // мере того, как компоненты будут реально появляться на экранах.
});
